#!/usr/bin/env python3
"""Build brand/flock-frames.js: the hero's flock clip as tile data.

brand/flock-pink.mp4 is a tile animation: five sea angels on a 44 by 31 grid
(20 px pitch, the first tile at 13, 11), each tile dark, pink, or light,
changing on keyframes held 5, 7, or 13 frames at 30 fps, then a crossfade
back to the start. This samples every frame at the tile centres, keeps the
keyframes before the crossfade with how long each is held, and writes them
packed two bits a tile, so brand/flock.js can draw the clip live and crisp
at any size. Standard library only; it needs ffmpeg on the PATH.

Run it after replacing the clip, and commit the result:

    python3 scripts/build-flock.py
"""
import base64
import os
import subprocess

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
CLIP = os.path.join(ROOT, "brand", "flock-pink.mp4")
OUT = os.path.join(ROOT, "brand", "flock-frames.js")

W, H = 900, 620
COLS, ROWS = 44, 31
PITCH, X0, Y0, TILE = 20, 13, 11, 17
FPS = 30


def tile_state(frame, c, r):
    """0 dark, 1 pink, 2 light, from a 3 by 3 patch at the tile's centre."""
    x = X0 + c * PITCH + TILE // 2
    y = min(Y0 + r * PITCH + TILE // 2, H - 3)
    red = green = 0
    for dy in (-2, 0, 2):
        for dx in (-2, 0, 2):
            i = ((y + dy) * W + x + dx) * 3
            red += frame[i]
            green += frame[i + 1]
    red, green = red / 9, green / 9
    if red < 90:
        return 0
    return 2 if green > 150 else 1


def crossfading(frame):
    """A frame in the closing crossfade has tiles between the three colours."""
    mixed = 0
    for r in range(ROWS):
        for c in range(COLS):
            x = X0 + c * PITCH + TILE // 2
            y = min(Y0 + r * PITCH + TILE // 2, H - 3)
            i = (y * W + x) * 3
            red, green = frame[i], frame[i + 1]
            if 90 <= red < 200 or (red > 200 and 90 < green < 150):
                mixed += 1
    return mixed > 10


def main():
    ff = subprocess.Popen(
        ["ffmpeg", "-v", "error", "-i", CLIP, "-f", "rawvideo", "-pix_fmt", "rgb24", "-"],
        stdout=subprocess.PIPE,
    )
    keys, holds = [], []
    size = W * H * 3
    while True:
        frame = ff.stdout.read(size)
        if len(frame) < size or crossfading(frame):
            break
        states = bytes(tile_state(frame, c, r) for r in range(ROWS) for c in range(COLS))
        if keys and keys[-1] == states:
            holds[-1] += 1
        else:
            keys.append(states)
            holds.append(1)
    ff.kill()

    packed = bytearray()
    for key in keys:
        for i in range(0, len(key), 4):
            quad = key[i:i + 4].ljust(4, b"\0")
            packed.append(quad[0] | quad[1] << 2 | quad[2] << 4 | quad[3] << 6)
    ms = [round(h * 1000 / FPS) for h in holds]
    with open(OUT, "w") as f:
        f.write("/* Generated by scripts/build-flock.py from brand/flock-pink.mp4: edit\n")
        f.write("   the clip and rerun it, not this file. Each keyframe is COLS * ROWS\n")
        f.write("   tiles, two bits a tile (0 dark, 1 pink, 2 light), four tiles a byte,\n")
        f.write("   row by row; hold is how long each keyframe shows, in ms. */\n")
        f.write("window.spawnpointFlock = {\n")
        f.write("  cols: %d, rows: %d,\n" % (COLS, ROWS))
        f.write("  hold: [%s],\n" % ", ".join(str(m) for m in ms))
        f.write('  keys: "%s"\n' % base64.b64encode(bytes(packed)).decode())
        f.write("};\n")
    print("wrote %s: %d keyframes, %d bytes packed" % (os.path.relpath(OUT, ROOT), len(keys), len(packed)))


if __name__ == "__main__":
    main()
